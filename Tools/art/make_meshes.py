"""カードと卓の板ポリゴン（.obj / .mtl）を生成する。

エンジンには使える組み込みプリミティブが無いため、ここで作って ModelImporter に読ませる。
座標系はエンジンと同じ左手系・Y 上。単位は 1 = 1mm 相当（影のカスケード解像度に合う大きさ）。

    python Tools/art/make_meshes.py

カード:
    XZ 平面に寝かせた薄い板。表面（マテリアル Front）が +Y、裏面（Back）が -Y を向く。
    絵の上端が +Z（奥）側。裏返しは Z 軸まわりの 180° 回転で行う。
卓:
    y = 0 の板。表面が +Y。
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "ChronoSort" / "Assets" / "Meshes"

CARD_WIDTH = 64.0       # カード幅（512px の面に対応）
CARD_HEIGHT = 96.0      # カード高さ（768px の面に対応）
CARD_THICKNESS = 0.6    # 表と裏の間隔

TABLE_WIDTH = 1600.0
TABLE_DEPTH = 1000.0


def quad_up(y, half_w, half_d, flip_u=False):
    """+Y を向いた四角形の頂点（左下・左上・右上・右下）と UV を返す。

    D3D の既定（時計回りが表）で上から見て時計回りになる順に並べる。
    """
    positions = [(-half_w, y, -half_d), (-half_w, y, half_d), (half_w, y, half_d), (half_w, y, -half_d)]
    uvs = [(0.0, 0.0), (0.0, 1.0), (1.0, 1.0), (1.0, 0.0)]
    if flip_u:
        uvs = [(1.0 - u, v) for u, v in uvs]
    return positions, uvs


def write_obj(name, groups):
    """groups: [(マテリアル名, 頂点4つ, UV4つ, 法線, 時計回りか)] を .obj と .mtl に書き出す。"""
    obj_lines = [f"# generated by Tools/art/make_meshes.py", f"mtllib {name}.mtl"]
    mtl_lines = ["# generated by Tools/art/make_meshes.py"]
    index = 1
    for normal_index, (material, positions, uvs, normal, clockwise) in enumerate(groups, start=1):
        obj_lines.append(f"g {material}")
        obj_lines.append(f"usemtl {material}")
        for x, y, z in positions:
            obj_lines.append(f"v {x:.4f} {y:.4f} {z:.4f}")
        for u, v in uvs:
            obj_lines.append(f"vt {u:.4f} {v:.4f}")
        obj_lines.append(f"vn {normal[0]:.1f} {normal[1]:.1f} {normal[2]:.1f}")
        a, b, c, d = (index + i for i in range(4))
        tris = [(a, b, c), (a, c, d)] if clockwise else [(a, c, b), (a, d, c)]
        for t in tris:
            obj_lines.append("f " + " ".join(f"{i}/{i}/{normal_index}" for i in t))
        index += 4
        mtl_lines += [f"newmtl {material}", "Kd 1.0 1.0 1.0", ""]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / f"{name}.obj").write_text("\n".join(obj_lines) + "\n", encoding="utf-8")
    (OUT_DIR / f"{name}.mtl").write_text("\n".join(mtl_lines) + "\n", encoding="utf-8")


def main():
    half_t = CARD_THICKNESS / 2
    front_pos, front_uv = quad_up(half_t, CARD_WIDTH / 2, CARD_HEIGHT / 2)
    # 裏面は下から見て正しく読めるよう U を反転し、巻き順も逆にする
    back_pos, back_uv = quad_up(-half_t, CARD_WIDTH / 2, CARD_HEIGHT / 2, flip_u=True)
    write_obj("card", [
        ("Front", front_pos, front_uv, (0, 1, 0), True),
        ("Back", back_pos, back_uv, (0, -1, 0), False),
    ])

    table_pos, table_uv = quad_up(0.0, TABLE_WIDTH / 2, TABLE_DEPTH / 2)
    write_obj("table", [("Table", table_pos, table_uv, (0, 1, 0), True)])
    print(f"wrote meshes to {OUT_DIR}")


if __name__ == "__main__":
    main()
